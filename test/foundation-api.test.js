'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { mkdtempSync, rmSync } = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Domain = require('../shared/domain');
const dir = mkdtempSync(path.join(os.tmpdir(), 'wordmaster-foundation-'));
process.env.WORDMASTER_DB_PATH = path.join(dir, 'test.db');
const { app, db } = require('../app/main');

test('daily plans, overdue fallback, import previews and POS scopes behave consistently', async t => {
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.close(); await once(server, 'close'); db.close(); rmSync(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const id = Number(db.prepare("INSERT INTO wordbooks(name) VALUES('测试词库')").run().lastInsertRowid);
  const send = (url, body, method = 'POST') => fetch(base + url, { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const text = '"record",n.,"记录,档案"\napple\t\t苹果\nweb 3 n. 自建词条\n错误行\nrecord,n.,重复';
  let response = await send(`/api/books/${id}/import/preview`, { text });
  const preview = await response.json();
  assert.equal(preview.added, 3); assert.equal(preview.dup, 1); assert.equal(preview.bad[0].line, 4);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM words').get().n, 0, 'preview is read-only');
  response = await send(`/api/books/${id}/import`, { text });
  assert.equal((await response.json()).added, 3);
  response = await send(`/api/books/${id}/plan`, { mode: 'daily', daily_new: 2 }, 'PUT');
  let plan = (await response.json()).plan;
  assert.equal(plan.mode, 'daily'); assert.equal(plan.daily_quota, 2); assert.equal(plan.days_left, 2);
  const today = await (await fetch(`${base}/api/desktop/books/${id}/today`)).json();
  assert.equal(today.learn.length, 2);
  for (const invalid of [0, 51, 2.5, '15']) assert.equal((await send(`/api/books/${id}/plan`, { mode: 'daily', daily_new: invalid }, 'PUT')).status, 400);
  db.prepare("UPDATE wordbooks SET plan_mode='date',target_date='2020-01-01',daily_new=2,plan_active=1 WHERE id=?").run(id);
  plan = (await (await fetch(`${base}/api/books`)).json()).find(b => b.id === id).plan;
  assert.equal(plan.status, 'overdue'); assert.equal(plan.days_left, 0); assert.equal(plan.daily_quota, 2);
  const expected = Domain.calculatePlan({ remainingNew: 31, dailyNew: 15, planActive: true, planMode: 'daily', now: new Date(2026, 9, 11) });
  assert.equal(expected.target_date, '2026-10-13');
  db.prepare("INSERT INTO words(book_id,word,pos,meaning) VALUES(?,'mixed','n.','词义 v. 动作')").run(id);
  const posWords = await (await fetch(`${base}/api/books/${id}/study?mode=pos`)).json();
  assert.ok(posWords.every(Domain.isUnambiguousPos));
  assert.equal((await send('/api/words', { book_id: id, word: '  ', meaning: '空词头' })).status, 400);
  const numbered = Number(db.prepare("INSERT INTO words(book_id,word,headword,homograph,source_file,meaning,pos) VALUES(?,'attribute 1','attribute',1,'cet6.txt','归因于','v.')").run(id).lastInsertRowid);
  assert.equal((await send(`/api/words/${numbered}`, { word: 'custom', meaning: '自定义', pos: 'n.' }, 'PUT')).status, 200);
  const edited = (await (await fetch(`${base}/api/books/${id}/words`)).json()).find(w => w.id === numbered);
  assert.equal(edited.word, 'custom'); assert.equal(edited.headword, null);
  db.prepare("INSERT INTO words(book_id,word,pos,meaning) VALUES(?,'archive','n.','档案；文件')").run(id);
  await send(`/api/books/${id}/plan`, { mode: 'daily', daily_new: 50 }, 'PUT');
  const meaningWords = await (await fetch(`${base}/api/books/${id}/study?mode=meaning`)).json();
  const record = meaningWords.find(w => w.word === 'record');
  assert.ok(record);
  assert.equal(record.choices.includes('档案；文件'), false, 'a distractor sharing an explicit correct sense is excluded');
});
